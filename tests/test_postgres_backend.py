from cne.db.database import (
    HybridRow,
    PostgresConnection,
    _postgres_placeholders,
    _postgres_schema,
)


def test_postgres_schema_translates_sqlite_types_and_constraints():
    schema = _postgres_schema()

    assert "PRAGMA" not in schema
    assert "AUTOINCREMENT" not in schema
    assert "INTEGER" not in schema
    assert " REAL" not in schema
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in schema
    assert "DOUBLE PRECISION" in schema
    assert "CREATE TRIGGER IF NOT EXISTS" not in schema
    assert "BEFORE UPDATE OR DELETE ON pre_release_preparations" in schema
    assert "CREATE TABLE IF NOT EXISTS scheduler_log" in schema


def test_hybrid_row_supports_name_and_position_access():
    row = HybridRow({"release_id": 17, "symbol": "XAU/USD"})

    assert row["release_id"] == row[0] == 17
    assert row["symbol"] == row[1] == "XAU/USD"
    assert dict(row) == {"release_id": 17, "symbol": "XAU/USD"}


def test_postgres_placeholder_conversion_supports_positional_and_named_parameters():
    assert _postgres_placeholders("SELECT * FROM t WHERE id=?::bigint", (1,)) == (
        "SELECT * FROM t WHERE id=%s::bigint"
    )
    assert _postgres_placeholders(
        "INSERT INTO t (name) VALUES (:name)", {"name": "value"}
    ) == "INSERT INTO t (name) VALUES (%(name)s)"


def test_postgres_executemany_converts_named_parameter_batches():
    class Cursor:
        def executemany(self, query, params):
            self.query = query
            self.params = list(params)

    class Connection:
        def __init__(self):
            self.cursor_instance = Cursor()

        def cursor(self, row_factory):
            return self.cursor_instance

    connection = Connection()
    PostgresConnection(connection).executemany(
        "INSERT INTO t (name) VALUES (:name)",
        [{"name": "first"}, {"name": "second"}],
    )

    assert connection.cursor_instance.query == (
        "INSERT INTO t (name) VALUES (%(name)s)"
    )
    assert connection.cursor_instance.params == [
        {"name": "first"},
        {"name": "second"},
    ]
